/**
 * FormFlow - Photo & Signature Image Optimization Engine
 * File: /extension/ui/imageFixer.js
 *
 * Normalizes student passport photos and scanned signatures to match official portal specifications:
 * - Center-crops to exact width and height without stretching or distorting aspect ratios.
 * - Progressively optimizes compression quality to meet strict maxKB limits.
 * - In-memory only: zero persistent storage of biometric photos or signatures.
 *
 * PRIVACY & SECURITY DEFENSE:
 * Drawing image pixels onto an HTML5 Canvas and re-encoding as a fresh JPEG completely strips
 * all EXIF metadata (GPS coordinates, device models, capture timestamps) and neutralizes any
 * steganographic payloads or malformed headers embedded in the original file.
 * Object URLs are used solely for immediate DOM previews and must always be explicitly revoked.
 */

(function (root) {
  'use strict';

  // Ensure FormFlow and UI namespaces exist
  root.FormFlow = root.FormFlow || {};
  root.FormFlow.ui = root.FormFlow.ui || {};

  // Progression of compression qualities to test for meeting portal maxKB thresholds
  var QUALITY_STEPS = [0.92, 0.85, 0.75, 0.65, 0.55, 0.45, 0.35];

  // Active object URL registry to guarantee clean memory revocation
  var activeObjectUrls = new Set();

  /**
   * Generates a tracked object URL for temporary DOM preview.
   * @param {Blob|File} blob
   * @returns {string} Object URL.
   */
  function createSafeObjectURL(blob) {
    if (!blob) return '';
    var url = URL.createObjectURL(blob);
    activeObjectUrls.add(url);
    return url;
  }

  /**
   * Revokes a specific object URL to prevent memory leaks.
   * @param {string} url
   */
  function revokeSafeObjectURL(url) {
    if (url) {
      try {
        URL.revokeObjectURL(url);
      } catch (err) {
        // Ignore revocation errors
      }
      activeObjectUrls.delete(url);
    }
  }

  /**
   * Revokes all active object URLs generated by imageFixer.
   */
  function revokeAllSafeObjectURLs() {
    activeObjectUrls.forEach(function (url) {
      try {
        URL.revokeObjectURL(url);
      } catch (err) {
        // Ignore revocation errors
      }
    });
    activeObjectUrls.clear();
  }

  /**
   * Loads an image file into an HTMLImageElement in memory.
   * @param {File|Blob} file
   * @returns {Promise<HTMLImageElement>}
   */
  function loadImageElement(file) {
    return new Promise(function (resolve, reject) {
      var img = new Image();
      var tempUrl = URL.createObjectURL(file);

      img.onload = function () {
        URL.revokeObjectURL(tempUrl);
        resolve(img);
      };

      img.onerror = function () {
        URL.revokeObjectURL(tempUrl);
        reject(new Error('Failed to decode image file.'));
      };

      img.src = tempUrl;
    });
  }

  /**
   * Converts a canvas element into a Blob at a given JPEG quality.
   * @param {HTMLCanvasElement} canvas
   * @param {number} quality Float between 0.0 and 1.0.
   * @returns {Promise<Blob>}
   */
  function canvasToBlob(canvas, quality) {
    return new Promise(function (resolve, reject) {
      canvas.toBlob(function (blob) {
        if (blob) {
          resolve(blob);
        } else {
          reject(new Error('Canvas toBlob conversion failed.'));
        }
      }, 'image/jpeg', quality);
    });
  }

  /**
   * Resizes, center-crops, and compresses a photo or signature to meet portal specifications.
   *
   * @param {File} file The original user-selected file.
   * @param {Object} spec Portal specification: { widthPx, heightPx, maxKB, formats }
   * @returns {Promise<{ blob: Blob, widthPx: number, heightPx: number, sizeKB: number, originalSizeKB: number, quality: number }|{ error: string }>}
   */
  function fixImage(file, spec) {
    return new Promise(function (resolve) {
      if (!file) {
        resolve({ error: 'No image file provided.' });
        return;
      }

      if (!spec || typeof spec.widthPx !== 'number' || typeof spec.heightPx !== 'number' || typeof spec.maxKB !== 'number') {
        resolve({ error: 'Invalid portal specification parameters.' });
        return;
      }

      // STEP 1: Pre-flight security verification via uploadChecks.js
      var checkPromise = (root.FormFlow.ui && typeof root.FormFlow.ui.checkUpload === 'function')
        ? root.FormFlow.ui.checkUpload(file)
        : Promise.resolve({ ok: true });

      checkPromise.then(function (checkRes) {
        if (!checkRes || !checkRes.ok) {
          var errMsg = (checkRes && checkRes.message) ? checkRes.message : 'File validation failed.';
          resolve({ error: errMsg });
          return;
        }

        // STEP 2: Decode image into an in-memory element
        loadImageElement(file).then(function (img) {
          var targetW = spec.widthPx;
          var targetH = spec.heightPx;
          var srcW = img.naturalWidth || img.width;
          var srcH = img.naturalHeight || img.height;

          if (srcW === 0 || srcH === 0) {
            resolve({ error: 'Image has invalid dimensions.' });
            return;
          }

          // STEP 3: Compute center-crop coordinates to NEVER stretch
          var targetAspect = targetW / targetH;
          var srcAspect = srcW / srcH;
          var cropX = 0;
          var cropY = 0;
          var cropW = srcW;
          var cropH = srcH;

          if (srcAspect > targetAspect) {
            // Source is wider than target: crop horizontal sides
            cropW = Math.round(srcH * targetAspect);
            cropX = Math.round((srcW - cropW) / 2);
          } else if (srcAspect < targetAspect) {
            // Source is taller than target: crop top/bottom
            cropH = Math.round(srcW / targetAspect);
            cropY = Math.round((srcH - cropH) / 2);
          }

          // Render onto canvas at exact target resolution
          var canvas = document.createElement('canvas');
          canvas.width = targetW;
          canvas.height = targetH;
          var ctx = canvas.getContext('2d');

          // Fill solid white background (handles transparent PNGs cleanly)
          ctx.fillStyle = '#FFFFFF';
          ctx.fillRect(0, 0, targetW, targetH);

          // Center-crop draw
          ctx.drawImage(img, cropX, cropY, cropW, cropH, 0, 0, targetW, targetH);

          var originalSizeKB = Math.round((file.size / 1024) * 10) / 10;

          // STEP 4: Progressive compression loop through quality steps
          function tryQuality(index) {
            if (index >= QUALITY_STEPS.length) {
              resolve({
                error: 'Unable to compress image under ' + spec.maxKB + ' KB at ' + targetW + 'x' + targetH + 'px without excessive degradation.'
              });
              return;
            }

            var q = QUALITY_STEPS[index];
            canvasToBlob(canvas, q).then(function (blob) {
              var sizeKB = Math.round((blob.size / 1024) * 10) / 10;
              if (sizeKB <= spec.maxKB) {
                // Success: within threshold
                resolve({
                  blob: blob,
                  widthPx: targetW,
                  heightPx: targetH,
                  sizeKB: sizeKB,
                  originalSizeKB: originalSizeKB,
                  quality: q
                });
              } else {
                // Try next lower quality step
                tryQuality(index + 1);
              }
            }).catch(function (blobErr) {
              resolve({ error: 'Canvas encoding failed: ' + blobErr.message });
            });
          }

          tryQuality(0);
        }).catch(function (loadErr) {
          resolve({ error: loadErr.message || 'Unable to decode image file.' });
        });
      }).catch(function () {
        resolve({ error: 'Pre-flight file check encountered an error.' });
      });
    });
  }

  // Expose to window.FormFlow.ui
  root.FormFlow.ui.fixImage = fixImage;
  root.FormFlow.ui.createSafeObjectURL = createSafeObjectURL;
  root.FormFlow.ui.revokeSafeObjectURL = revokeSafeObjectURL;
  root.FormFlow.ui.revokeAllSafeObjectURLs = revokeAllSafeObjectURLs;

  // Support CommonJS testing environments
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = {
      fixImage: fixImage,
      createSafeObjectURL: createSafeObjectURL,
      revokeSafeObjectURL: revokeSafeObjectURL,
      revokeAllSafeObjectURLs: revokeAllSafeObjectURLs,
      QUALITY_STEPS: QUALITY_STEPS
    };
  }
})(typeof self !== 'undefined' ? self : this);
